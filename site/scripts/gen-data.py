"""Builds site/src/data.ts from benchmark/results/<model>/*.json.

python3 site/scripts/gen-data.py
"""

import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, "benchmark", "tools"))
from compare_quality import compare  # noqa: E402

RES = os.path.join(ROOT, "benchmark", "results")

MODELS = {
    "cosmos3": {
        "tpu": "result_v6e-4-bf16.json",
        "h100": "result_h100_bf16.json",
        "fp8": "result_h100_fp8.json",
        "examples": ["000_02678d04_315969912349927217.jpg", "012_15ec0778_315970267899927219.jpg"],
    },
    "qwen38": {
        "tpu": "result_qwen38-v6e-4-bf16.json",
        "h100": "result_qwen38-h100-bf16.json",
        "fp8": "result_qwen38-h100-fp8.json",
        "examples": ["000_02678d04_315969912349927217.jpg", "012_15ec0778_315970267899927219.jpg"],
    },
}


def load(model, key):
    p = os.path.join(RES, model, MODELS[model][key])
    return (json.load(open(p)), p) if os.path.exists(p) else (None, None)


def r3(x):
    return None if x is None else round(x, 3)


out = {}
for model, cfg in MODELS.items():
    (t, tp), (b, bp), (f, fp) = load(model, "tpu"), load(model, "h100"), load(model, "fp8")
    if not t:
        continue
    lv = lambda d: {l["concurrency"]: l for l in d["levels"]} if d else {}
    T, B, F = lv(t), lv(b), lv(f)
    rows = []
    for c in sorted(set(T) | set(B) | set(F)):
        g = lambda D, k: r3(D[c][k]) if c in D else None
        rows.append({
            "concurrency": c,
            "tpu": g(T, "out_tok_per_s"), "h100": g(B, "out_tok_per_s"), "h100fp8": g(F, "out_tok_per_s"),
            "tpuTtft": g(T, "ttft_p50_s"), "h100Ttft": g(B, "ttft_p50_s"), "h100fp8Ttft": g(F, "ttft_p50_s"),
            "tpuTpot": g(T, "tpot_p50_ms"), "h100Tpot": g(B, "tpot_p50_ms"), "h100fp8Tpot": g(F, "tpot_p50_ms"),
        })
    strip = lambda q: {k: v for k, v in q.items() if k not in ("ref", "cand")}
    quality = {}
    if b:
        quality["tpu"] = strip(compare(bp, tp))
        if fp:
            quality["fp8"] = strip(compare(bp, fp))
    examples = []
    for k in cfg["examples"]:
        if k in t["samples"]:
            examples.append({
                "file": k[:3] + ".jpg", "source": k, "tpu": t["samples"][k],
                "h100": (b or {}).get("samples", {}).get(k), "fp8": (f or {}).get("samples", {}).get(k),
            })
    prompt_tokens = next((l["mean_prompt_tokens"] for l in t["levels"] if l.get("mean_prompt_tokens")), None)
    out[model] = {"levels": rows, "quality": quality, "examples": examples, "promptTokens": prompt_tokens,
                  "h100Pending": b is None}

ts = "// Generated by site/scripts/gen-data.py from benchmark/results/<model>/*.json\n\n"
ts += "export type Level = {\n  concurrency: number\n" + "".join(
    f"  {k}: number | null\n" for k in ["tpu", "h100", "h100fp8", "tpuTtft", "h100Ttft", "h100fp8Ttft", "tpuTpot", "h100Tpot", "h100fp8Tpot"]
) + "}\n\n"
ts += "export type Example = { file: string; source: string; tpu: string; h100: string | null; fp8: string | null }\n\n"
ts += ("export type Quality = { images: number; exact_match: string; mean_char_similarity: number; "
       "mean_identical_prefix_frac: number; field_agreement: string }\n\n")
ts += ("export type ModelData = { levels: Level[]; quality: { tpu?: Quality; fp8?: Quality }; examples: Example[]; "
       "promptTokens: number | null; h100Pending: boolean }\n\n")
ts += "export const results: Record<string, ModelData> = " + json.dumps(out, indent=2) + "\n"
open(os.path.join(ROOT, "site", "src", "data.ts"), "w").write(ts)
print("models:", list(out))
